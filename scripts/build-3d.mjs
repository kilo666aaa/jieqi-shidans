import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const outputFile = 'js/vendor/courtyard-3d.js';
const result = await build({
  entryPoints: ['src/courtyard-3d.jsx'],
  bundle: true,
  format: 'iife',
  globalName: 'Jieqi3D',
  outfile: outputFile,
  minify: true,
  legalComments: 'linked',
  metafile: true,
  target: ['es2020'],
  define: { 'process.env.NODE_ENV': '"production"' },
  footer: {
    js: '/* Full dependency license texts: courtyard-3d.LICENSES.txt */'
  }
});

await writeFile(`${outputFile}.meta.json`, `${JSON.stringify(result.metafile, null, 2)}\n`);

const packageRoots = new Set();
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, contribution] of Object.entries(output.inputs)) {
    if (!contribution.bytesInOutput) continue;
    const normalized = input.replaceAll('\\', '/');
    const match = normalized.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)/);
    if (match) packageRoots.add(match[1]);
  }
}

const sections = [];
// Fiber's npm tarball omits LICENSE. Keep the exact release's upstream text
// locally so subsequent builds remain reproducible and require no network.
const upstreamLicenses = {
  '@react-three/fiber@9.8.2': {
    file: 'scripts/licenses/react-three-fiber-9.8.2.LICENSE.txt',
    source: 'https://raw.githubusercontent.com/pmndrs/react-three-fiber/v9.8.2/LICENSE'
  }
};

for (const root of [...packageRoots].sort()) {
  const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const identity = `${manifest.name}@${manifest.version}`;
  const files = (await readdir(root)).filter(name => /^licen[cs]e(?:\.(?:md|txt))?$/i.test(name));
  const texts = await Promise.all(files.map(async name => {
    const text = await readFile(path.join(root, name), 'utf8');
    return `Source: ${root}/${name}\n\n${text.trim()}`;
  }));

  if (!texts.length && upstreamLicenses[identity]) {
    const upstream = upstreamLicenses[identity];
    const text = await readFile(upstream.file, 'utf8');
    texts.push(`Source: ${upstream.source}\nLocal copy: ${upstream.file}\n\n${text.trim()}`);
  }
  if (!texts.length) {
    throw new Error(`Missing full license text for ${identity}`);
  }

  sections.push(`${'='.repeat(78)}\n${identity}\nDeclared license: ${manifest.license || 'See text below'}\n${'='.repeat(78)}\n\n${texts.join('\n\n')}`);
}

const licenseFile = 'js/vendor/courtyard-3d.LICENSES.txt';
await writeFile(licenseFile, `Full license notices for ${packageRoots.size} bundled packages.\nGenerated by scripts/build-3d.mjs from the esbuild metafile.\n\n${sections.join('\n\n')}\n`);
console.log(`Built ${outputFile}; collected full licenses for ${packageRoots.size} bundled packages.`);
